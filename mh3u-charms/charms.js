  function parseSkills(text) {
    const lines = text.trim().split("\n");
    const skills = new Map();
    const limit = lines.length;
    for (let i = 1; i !== limit; i++) {
      const line = lines[i].trim();
      if (!line) continue;
      const parts = line.split(",");
      const id = parseInt(parts[1], 10);
      const name = parts[3];
      if (!isNaN(id) && name) {
        skills.set(id, name);
      }
    }
    return skills;
  }

  const EQ_BOX_OFFSET = 0x1150;
  const NUM_EQ_SLOTS = 1000;
  const CHARM_ID = 6;
  const SAVE_FILE_SIZE = 35364;

  function parseCharms(buffer) {
    const view = new DataView(buffer);
    const charms = [];

    for (let i = 0; i !== NUM_EQ_SLOTS; i++) {
      const offset = EQ_BOX_OFFSET + i * 16;
      if (offset + 8 > view.byteLength) break;

      const id = view.getUint8(offset);
      if (id === CHARM_ID) {
        const slots = view.getUint8(offset + 1);
        const type = view.getUint8(offset + 3);
        const skill1 = view.getUint8(offset + 4);
        const pt1 = view.getInt8(offset + 5);
        const skill2 = view.getUint8(offset + 6);
        const pt2 = view.getInt8(offset + 7);

        charms.push({ type, slots, skill1, pt1, skill2, pt2 });
      }
    }
    return charms;
  }

  function generateCSV(charms, skills) {
    const lines = [];
    for (const c of charms) {
      let line = c.type + "," + c.slots;
      if (c.skill1 !== 0) {
        line += "," + (skills.get(c.skill1) || "?") + "," + c.pt1;
      }
      if (c.skill2 !== 0) {
        line += "," + (skills.get(c.skill2) || "?") + "," + c.pt2;
      }
      lines.push(line);
    }
    return lines.join("\r\n");
  }

  function encodeShiftJIS(str) {
    const bytes = [];
    const limit = str.length;
    for (let i = 0; i !== limit; i++) {
      const code = str.charCodeAt(i);
      if (code < 0x80) {
        bytes.push(code);
      } else {
        const sjis = SJIS_TABLE.get(code);
        if (sjis) {
          bytes.push((sjis >> 8) & 0xFF, sjis & 0xFF);
        } else {
          bytes.push(0x3F); // "?" fallback
        }
      }
    }
    return new Uint8Array(bytes);
  }

